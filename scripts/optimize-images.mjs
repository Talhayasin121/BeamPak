import {mkdirSync,readFileSync,writeFileSync,statSync} from 'node:fs';
import sharp from 'sharp';

const out='web/media/fast';
mkdirSync(out,{recursive:true});
const images=[
 {name:'pod',file:'rgb-pod-single.png',widths:[160,320,640,960],lossless:true,pngWidth:640},
 {name:'accessories',file:'led-kit-accessories.png',widths:[384,768],lossless:true,pngWidth:768},
 {name:'hero',file:'hero.jpg',widths:[160,640,1280,1920]},
 {name:'civic',file:'hero-civic-2025.jpg',widths:[160,640,1280]},
 {name:'grande',file:'hero-grande-2025.jpg',widths:[160,640,1280]},
 {name:'carUse',file:'led-pod-civic-detail.jpg',widths:[160,640,1100]},
 {name:'bikeUse',file:'led-pod-bike-detail.jpg',widths:[160,640,1100]},
 {name:'kit',file:'rgb-pods.jpg',widths:[160,640]}
];
const manifest={};
for(const image of images){
 const variants=[];
 for(const width of image.widths){
  const target=out+'/'+image.name+'-'+width+'.webp';
  const info=await sharp('web/media/'+image.file).resize({width,withoutEnlargement:true}).webp({lossless:Boolean(image.lossless),quality:85,effort:6}).toFile(target);
  variants.push({src:'/media/fast/'+image.name+'-'+width+'.webp',width:info.width,height:info.height,bytes:info.size});
 }
 let fallback='/media/'+image.file;
 if(image.pngWidth) {
  const name=image.name+'-'+image.pngWidth+'.png';
  await sharp('web/media/'+image.file).resize({width:image.pngWidth,withoutEnlargement:true}).png({compressionLevel:9}).toFile(out+'/'+name);
  fallback='/media/fast/'+name;
 }
 manifest[image.name]={fallback,originalBytes:statSync('web/media/'+image.file).size,variants};
}
writeFileSync('web/media-assets.js','// Generated by npm run optimize:images. Original artwork is retained.\nexport const mediaAssets = '+JSON.stringify(manifest,null,2)+';\n');
console.log(JSON.stringify(Object.fromEntries(Object.entries(manifest).map(([name,item])=>[name,{original:item.originalBytes,variants:item.variants.map(({width,bytes})=>({width,bytes}))}])),null,2));
